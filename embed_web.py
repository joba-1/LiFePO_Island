# Pre-build: embed web/index.html and web/logo.svg into the firmware.
#
# Writes $BUILD_DIR/generated/web_assets.h with one C string per file
# (WEB_INDEX_HTML, WEB_LOGO_SVG) and adds that directory to the include path.
# The files are edited as plain HTML/SVG; the firmware can never serve a
# stale copy. See docs/spec-webui.md.
import os

Import("env")  # noqa: F821

ASSETS = [("web/index.html", "WEB_INDEX_HTML"), ("web/logo.svg", "WEB_LOGO_SVG")]

project = env.subst("$PROJECT_DIR")  # noqa: F821
out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
os.makedirs(out_dir, exist_ok=True)

lines = ["// generated by embed_web.py - do not edit", "#pragma once", ""]
for rel, name in ASSETS:
    with open(os.path.join(project, rel), "rb") as f:
        data = f.read()
    # hex escapes: no delimiter or trigraph surprises, any byte allowed
    body = "".join("\\x%02x" % b for b in data)
    chunks = [body[i:i + 160] for i in range(0, len(body), 160)]
    lines.append("static const char %s[] =" % name)
    lines.extend('    "%s"' % c for c in chunks)
    lines.append("    ;")
    lines.append("")

path = os.path.join(out_dir, "web_assets.h")
text = "\n".join(lines)
old = open(path).read() if os.path.exists(path) else None
if old != text:  # keep the timestamp when nothing changed: no needless rebuild
    with open(path, "w") as f:
        f.write(text)
env.Append(CPPPATH=[out_dir])  # noqa: F821
